import { PaperAnalysis } from '../types';

export function generateMarkdown(analysis: PaperAnalysis, originalFileName?: string): string {
  const meta = analysis.metadata;
  const title = meta.title || originalFileName?.replace(/\.pdf$/i, '') || 'Research Paper';
  const authors = meta.authors && meta.authors.length > 0 ? meta.authors.join(', ') : 'Not found in paper.';
  const year = meta.year ? meta.year.toString() : 'Not found in paper.';
  const venue = meta.venue || 'Not found in paper.';
  const keywords = analysis.keywords && analysis.keywords.length > 0 ? analysis.keywords.join(', ') : 'Not found in paper.';

  let md = `# ${title}\n\n`;
  md += `**Authors:** ${authors}  \n`;
  md += `**Year:** ${year}  \n`;
  md += `**Venue / Archive:** ${venue}  \n`;
  md += `**Keywords:** ${keywords}  \n\n`;
  md += `---\n\n`;

  md += `## 1. Overview\n\n`;
  md += `### Executive Summary\n${analysis.summary || 'Not found in paper.'}\n\n`;
  md += `### Research Problem\n${analysis.research_problem || 'Not found in paper.'}\n\n`;

  md += `## 2. Methodology\n\n`;
  md += `${analysis.methodology || 'Not found in paper.'}\n\n`;

  md += `## 3. Key Findings\n\n`;
  if (analysis.key_findings && analysis.key_findings.length > 0) {
    analysis.key_findings.forEach((kf, idx) => {
      md += `### Finding ${idx + 1}: ${kf.finding}\n`;
      md += `> "${kf.evidence_quote || 'Not found in paper.'}"\n\n`;
      md += `**Location in Paper:** ${kf.location || 'Not found in paper.'}\n\n`;
    });
  } else {
    md += `Not found in paper.\n\n`;
  }

  md += `## 4. Limitations\n\n`;
  if (analysis.limitations && analysis.limitations.length > 0) {
    analysis.limitations.forEach((lim, idx) => {
      const status = lim.stated_by_authors ? 'Acknowledged by authors' : 'Unstated by authors (inferred limitation)';
      const loc = lim.location ? ` (${lim.location})` : '';
      md += `- **[${status}${loc}]**: ${lim.limitation}\n`;
    });
    md += `\n`;
  } else {
    md += `Not found in paper.\n\n`;
  }

  md += `---\n*Generated by PaperLens — Academic Research Analysis*\n`;

  return md;
}

export function downloadMarkdownFile(content: string, filename: string) {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
